//! TypeScript type generator for `logos-types`.
//!
//! A zero-dependency, pure-stdlib Rust code generator.  It emits TypeScript
//! declarations that match the Rust structs in `logos-types` exactly.
//!
//! Run with:
//!   cargo run --bin generate-types
//!   make generate-rust-types
//!
//! Output: `logos-app/src/types/rust-generated/*.ts`
//!
//! # Future migration to ts-rs
//! Every public type already carries #[cfg_attr(feature = "ts", derive(ts_rs::TS))]
//! annotations.  When ts-rs is available in the registry, update Cargo.toml
//! and the switch from this hand-written emitter to ts-rs auto-generation is
//! a one-line change.  The struct annotations are already in place.

use std::collections::BTreeMap;
use std::path::PathBuf;

// ─────────────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────────────

const HEADER: &str = "/**\n\
 * @generated by rust/logos-types/src/bin/generate_types.rs\n\
 * Source:  rust/logos-types/src/\n\
 *\n\
 * DO NOT EDIT — run `make generate-rust-types` to regenerate.\n\
 */\n";

fn emit(files: &mut BTreeMap<&'static str, String>, name: &'static str, body: &str) {
    files.insert(name, format!("{HEADER}\n{body}"));
}

// ─────────────────────────────────────────────────────────────────────────────
// TypeScript declarations — one block per source module
// ─────────────────────────────────────────────────────────────────────────────

fn geometry(f: &mut BTreeMap<&'static str, String>) {
    emit(f, "geometry.ts", r#"
/** 2-D point — mirrors `logos_layout::Point`. */
export interface Point {
  x: number;
  y: number;
}

/** Axis-aligned bounding box — mirrors `logos_layout::Rect`. */
export interface Bounds {
  x: number;
  y: number;
  width: number;
  height: number;
}

/**
 * 6-element CSS affine matrix `[a, b, c, d, e, f]`
 * — mirrors `logos_layout::Matrix`.
 */
export type Transform = [number, number, number, number, number, number];
"#);
}

fn color(f: &mut BTreeMap<&'static str, String>) {
    emit(f, "color.ts", r#"
export type GradientType = "linear" | "radial";

export interface GradientStop {
  /** CSS `#rrggbb` hex color string. */
  color: string;
  opacity: number;
  /** Position along the gradient, `[0, 1]`. */
  offset: number;
}

export interface Gradient {
  gradientType: GradientType;
  /** Start point X in shape-local coords `[0, 1]`. */
  startX: number;
  startY: number;
  endX: number;
  endY: number;
  /** Radial gradient width (ignored for linear). */
  width?: number | null;
  stops: Array<GradientStop>;
  opacity: number;
}

/**
 * An RGBA color: hex `#rrggbb` + alpha `[0, 1]`.
 *
 * Optional `refId`/`refFile` link this color to a shared library entry.
 */
export interface Color {
  color: string;
  opacity: number;
  refId?: string | null;
  refFile?: string | null;
  name?: string | null;
  path?: string | null;
}
"#);
}

fn fill(f: &mut BTreeMap<&'static str, String>) {
    emit(f, "fill.ts", r#"
import type { Gradient } from "./color";

export interface FillImage {
  id: string;
  width: number;
  height: number;
  mtype?: string | null;
  name?: string | null;
  keepAspectRatio?: boolean | null;
}

/**
 * Fill applied to a shape.  Shapes carry multiple fills (`Array<Fill>`).
 * Discriminated by `fillType`.
 */
export type Fill =
  | { fillType: "solid";    color: string; opacity: number }
  | { fillType: "gradient"; gradient: Gradient; opacity: number }
  | { fillType: "image";    image: FillImage };
"#);
}

